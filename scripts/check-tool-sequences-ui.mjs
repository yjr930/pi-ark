import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { SessionManager } from "@earendil-works/pi-coding-agent";

const url = process.env.PI_ARK_CHECK_URL;
const workspace = process.env.PI_ARK_CHECK_WORKSPACE;
const workspaceId = process.env.PI_ARK_CHECK_WORKSPACE_ID || "pi_ark";
if (!url || !workspace) throw new Error("Set PI_ARK_CHECK_URL and PI_ARK_CHECK_WORKSPACE for an isolated service");
const screenshots = process.env.PI_ARK_CHECK_SCREENSHOT_DIR || "/tmp/pi-ark-tool-preview";
await mkdir(screenshots, { recursive: true });
const manager = SessionManager.create(workspace, join(workspace, ".pi-ark", "sessions"));
const usage = { input: 1200, output: 250, cacheRead: 300, cacheWrite: 0, totalTokens: 1750, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } };
const assistant = (content, stopReason = "toolUse") => ({ role: "assistant", content, api: "openai-responses", provider: "openai-codex", model: "gpt-5.6-sol", usage, stopReason, timestamp: Date.now() });
const call = (id) => ({ type: "toolCall", id, name: "read", arguments: { path: `docs/${id}.md` } });
const resultIds = [];
const tools = (ids, prefix = []) => {
  const entryId = manager.appendMessage(assistant([...prefix, ...ids.map(call)]));
  for (const id of ids) resultIds.push(manager.appendMessage({ role: "toolResult", toolCallId: id, toolName: "read", content: [{ type: "text", text: `Reviewed docs/${id}.md. The configuration uses shared global preferences.` }], isError: false, timestamp: Date.now() }));
  return entryId;
};
manager.appendSessionInfo("Tool display preview");
manager.appendMessage({ role: "system", content: "Use the shared Global settings. Keep explanations clear and preserve each tool call and its matching result.", timestamp: Date.now() });
manager.appendMessage({ role: "user", content: "Review the settings and conversation display changes.", timestamp: Date.now() - 20000 });
tools(["initial-check"], [{ type: "text", text: "I will review the configuration, then check the conversation display." }]);
for (let index = 1; index <= 5; index += 1) tools([`before-${index}`]);
const firstResultId = resultIds[1];
const compactionId = manager.appendCompaction("## Review progress\n\nGlobal preferences are shared by every Workspace. The remaining review covers tool grouping, message links, and responsive presentation.", null, 120000, { readFiles: ["docs/architecture.md"] }, false, usage);
manager.appendCustomEntry("pi-ark.compaction-timing", { compactionEntryId: compactionId, durationMs: 12500, reason: "threshold" });
tools(["after-1", "after-2", "after-3", "after-4", "after-5"]);
const mixedId = tools(["context-1", "context-2", "context-3", "context-4"], [{ type: "text", text: "The configuration review is complete. These checks have their own explanation." }]);
for (let index = 1; index <= 4; index += 1) tools([`next-${index}`]);
const reasoningId = tools(["reasoning-1", "reasoning-2", "reasoning-3", "reasoning-4"], [{ type: "thinking", thinking: "Keep calls with explanatory content outside the consecutive-call groups." }]);
manager.appendMessage(assistant([{ type: "text", text: "Review consecutive calls with hidden reasoning." }], "stop"));
let hiddenReasoningStart;
let reasoningOnlyId;
for (let index = 1; index <= 7; index += 1) {
  const entryId = tools([`hidden-reasoning-${index}`], [{ type: "thinking", thinking: `Review operation ${index} before execution.` }]);
  hiddenReasoningStart ||= entryId;
  if (index === 3) reasoningOnlyId = manager.appendMessage(assistant([{ type: "thinking", thinking: "Review the next operation independently." }]));
}
manager.appendMessage(assistant([{ type: "text", text: "The review is complete. Global preferences and conversation controls are ready for inspection." }], "stop"));
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, ignoreHTTPSErrors: true, permissions: ["clipboard-read", "clipboard-write"] });
const page = await context.newPage();

try {
  await page.addInitScript(() => { window.localStorage.setItem("pi-ark-appearance", JSON.stringify({ theme: "ark-dark", hideReasoning: false, markdownLineBreaks: true, fontScale: 1 })); });
  await page.goto(url);
  await page.getByLabel("Username").fill(process.env.PI_ARK_CHECK_USERNAME || "check");
  await page.getByLabel("Password").fill(process.env.PI_ARK_CHECK_PASSWORD || "check-password");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  const row = page.locator(".session-list-item").filter({ hasText: "Tool display preview" });
  await row.waitFor();
  await row.locator(".session-open").click();
  const run = page.locator(".run-collapse");
  await run.waitFor();
  if (await run.getAttribute("open") === null) await run.locator(":scope > summary").click();
  const groups = page.locator(".feed-tool-sequence");
  assert.equal(await groups.count(), 3);
  for (const group of await groups.all()) assert.equal(await group.locator(".feed-tool-item:visible").count(), 3);
  assert.equal(await page.locator(`[data-entry-id="${mixedId}"] .feed-tool-item:visible`).count(), 4);
  assert.equal(await page.locator(`[data-entry-id="${reasoningId}"] .feed-tool-item:visible`).count(), 4);
  const compact = page.locator(`[data-entry-id="${compactionId}"] .feed-tool-details`);
  assert.equal(await compact.locator("xpath=ancestor::*[contains(@class, 'feed-tool-sequence')]").count(), 0);
  const compactNeighbors = await compact.evaluate((element) => { const article = element.closest("article"); return [article.previousElementSibling?.classList.contains("feed-tool-sequence"), article.nextElementSibling?.classList.contains("feed-tool-sequence")]; });
  assert.deepEqual(compactNeighbors, [true, true]);
  const compactHeight = (await compact.boundingBox()).height;
  const normalHeight = (await groups.first().locator(".feed-tool-details:visible").first().boundingBox()).height;
  assert.equal(compactHeight, normalHeight * 3);
  assert.match(await compact.locator(":scope > summary").textContent(), /Compact.*Duration 12\.5s.*Before 120000.*After ≈\d+ tokens.*System prompt ≈\d+.*Summary ≈\d+.*Retained ≈\d+.*Saved/);
  await groups.first().getByRole("button", { name: "show more tool call", exact: true }).click();
  assert.equal(await groups.first().locator(".feed-tool-item:visible").count(), 5);
  assert.equal(await groups.nth(1).locator(".feed-tool-item:visible").count(), 3);
  await groups.first().getByRole("button", { name: "show less tool call", exact: true }).click();
  assert.equal(await groups.first().locator(".feed-tool-item:visible").count(), 3);
  await groups.nth(1).getByRole("button", { name: "show more tool call", exact: true }).click();
  assert.equal(await groups.nth(1).locator(".feed-tool-item:visible").count(), 5);
  await groups.nth(1).getByRole("button", { name: "show less tool call", exact: true }).click();
  const tool = groups.first().locator(".feed-tool-details:visible").first();
  await tool.locator(":scope > summary").click();
  const chip = tool.locator(".message-source-link").first();
  await chip.locator("code").hover();
  const tooltip = page.getByRole("tooltip");
  await tooltip.waitFor();
  assert.equal(await tooltip.evaluate((element) => element.parentElement === document.body), true);
  const tooltipBox = await tooltip.boundingBox();
  const chipBox = await chip.boundingBox();
  assert.ok(tooltipBox.y >= 0 && tooltipBox.x >= 0 && tooltipBox.x + tooltipBox.width <= 1440 && tooltipBox.y + tooltipBox.height <= chipBox.y);
  await chip.locator("code").click();
  await page.waitForFunction(() => navigator.clipboard.readText().then((text) => /pi-ark:\/\/workspace\/.+\/session\/.+\/message\/m[0-9a-z]{6}$/.test(text)));
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  const chipMessageId = await chip.evaluate((element) => element.closest("[data-message-id]")?.getAttribute("data-message-id") || "");
  assert.ok(chipMessageId && copied.endsWith(chipMessageId));
  assert.equal(await page.locator(".message-short-id").count(), 0);
  const toggleReasoning = async () => {
    await page.locator(".sidebar-navigation").getByRole("button", { name: "Settings", exact: true }).click();
    await page.getByRole("navigation", { name: "Settings categories" }).getByRole("button", { name: "Appearance", exact: true }).click();
    const hideReasoningSwitch = page.locator(".settings-row").filter({ hasText: "Hide reasoning" }).getByRole("switch");
    const hideReasoningBefore = await hideReasoningSwitch.getAttribute("aria-checked");
    const hideReasoningAfter = hideReasoningBefore === "false";
    await hideReasoningSwitch.click();
    await page.waitForFunction((expected) => { const value = window.localStorage.getItem("pi-ark-appearance"); return value ? JSON.parse(value).hideReasoning === expected : false; }, hideReasoningAfter);
    assert.equal(await hideReasoningSwitch.getAttribute("aria-checked"), String(hideReasoningAfter));
    await page.locator(".sidebar-navigation").getByRole("button", { name: "Agent", exact: true }).click();
    await run.waitFor();
    if (await run.getAttribute("open") === null) await run.locator(":scope > summary").click();
  };
  await toggleReasoning();
  assert.equal(await page.locator(".thinking").count(), 0);
  const reasoningGroup = page.locator(".feed-tool-sequence").filter({ has: page.locator(`[data-entry-id="${hiddenReasoningStart}"]`) });
  assert.equal(await reasoningGroup.count(), 1);
  assert.equal(await reasoningGroup.locator(".feed-tool-item:visible").count(), 3);
  assert.equal(await reasoningGroup.locator(`[data-entry-id="${reasoningOnlyId}"]`).count(), 1);
  assert.equal(await page.locator(`[data-entry-id="${mixedId}"] .feed-tool-item:visible`).count(), 4);
  await reasoningGroup.getByRole("button", { name: "show more tool call", exact: true }).click();
  assert.equal(await reasoningGroup.locator(".feed-tool-item:visible").count(), 7);
  await reasoningGroup.getByRole("button", { name: "show less tool call", exact: true }).click();
  assert.equal(await reasoningGroup.locator(".feed-tool-item:visible").count(), 3);
  await page.screenshot({ path: join(screenshots, "tools-hidden-reasoning-desktop.png") });
  await toggleReasoning();
  assert.equal(await reasoningGroup.count(), 0);
  assert.equal(await page.locator(`[data-entry-id="${hiddenReasoningStart}"] .thinking`).count(), 1);
  assert.equal(await page.locator(`[data-entry-id="${reasoningId}"] .feed-tool-item:visible`).count(), 4);
  await page.screenshot({ path: join(screenshots, "tools-desktop.png") });
  await compact.locator(":scope > summary").click();
  await compact.getByText("Compaction details", { exact: true }).waitFor();
  assert.match(await compact.locator(".compact-generation-details").textContent(), /threshold.*12\.5s.*1500.*250/);
  await compact.scrollIntoViewIfNeeded();
  await page.screenshot({ path: join(screenshots, "compact-desktop.png") });
  const earlyResultMessageId = await page.locator(`[data-entry-id="${firstResultId}"]`).getAttribute("data-message-id");
  const target = new URL(url);
  target.searchParams.set("workspace", workspaceId);
  target.searchParams.set("session", manager.getSessionId());
  target.searchParams.set("message", earlyResultMessageId);
  await page.goto(target.toString());
  await page.locator(".feed-tool-details.permalink-target[open]").waitFor();
  assert.equal(await page.locator(".feed-tool-sequence").first().getByRole("button", { name: "show less tool call", exact: true }).count(), 1);
  await page.setViewportSize({ width: 390, height: 844 });
  const closeSidebar = page.getByRole("button", { name: "Close sidebar", exact: true });
  if (await closeSidebar.isVisible()) await closeSidebar.click();
  await page.waitForFunction(() => document.querySelector(".sidebar").getBoundingClientRect().right <= 0);
  const compactMobile = page.locator(`[data-entry-id="${compactionId}"] .feed-tool-details`);
  await compactMobile.scrollIntoViewIfNeeded();
  const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  assert.equal(mobileOverflow, false);
  await page.screenshot({ path: join(screenshots, "tools-mobile.png") });
  console.log(`Tool sequence UI checks passed; screenshots: ${screenshots}`);
} catch (error) {
  await page.screenshot({ path: join(screenshots, "failure.png"), fullPage: true });
  throw error;
} finally { await browser.close(); }
