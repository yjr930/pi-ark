import assert from "node:assert/strict";
import { estimateTokens, SessionManager } from "@earendil-works/pi-coding-agent";
import { COMPACTION_TIMING_TYPE, compactionTimings } from "../apps/server/src/compaction-stats.ts";
import { buildSessionDisplayMessages } from "../apps/server/src/session-display.ts";

const manager = SessionManager.inMemory("/tmp/pi-ark-compaction-stats");
manager.appendMessage({ role: "system", content: "Global system instructions for the compaction fixture", timestamp: 1 });
manager.appendMessage({ role: "user", content: "Summarized conversation", timestamp: 2 });
const keptId = manager.appendMessage({ role: "user", content: "Retained conversation", timestamp: 3 });
const summary = "Compaction summary for the earlier conversation.";
const usage = { input: 1000, output: 200, cacheRead: 300, cacheWrite: 50, totalTokens: 1550, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } };
const compactionId = manager.appendCompaction(summary, keptId, 120000, { readFiles: ["README.md"] }, false, usage);
const beforeTiming = buildSessionDisplayMessages(manager).find((message) => message.entryId === compactionId)!;
assert.equal(beforeTiming.role, "compactionSummary");
assert.equal(beforeTiming.tokensBefore, 120000);
assert.equal(beforeTiming.compaction?.summaryTokens, Math.ceil(summary.length / 4));
assert.equal(beforeTiming.compaction?.retainedTokens, estimateTokens({ role: "user", content: "Retained conversation", timestamp: 3 }));
assert.ok(beforeTiming.compaction?.systemPromptTokens);
assert.equal(beforeTiming.compaction?.tokensAfter, beforeTiming.compaction!.systemPromptTokens! + beforeTiming.compaction!.summaryTokens + beforeTiming.compaction!.retainedTokens);
assert.equal(beforeTiming.compaction?.durationMs, undefined);
manager.appendCustomEntry(COMPACTION_TIMING_TYPE, { compactionEntryId: compactionId, durationMs: 12500, reason: "threshold" });
const withTiming = buildSessionDisplayMessages(manager).find((message) => message.entryId === compactionId)!;
assert.equal(withTiming.compaction?.durationMs, 12500);
assert.equal(withTiming.compaction?.reason, "threshold");
assert.equal(withTiming.compaction?.summarizerInputTokens, 1350);
assert.equal(withTiming.compaction?.summarizerOutputTokens, 200);
manager.appendMessage({ role: "system", content: "A later prompt must not change historical compaction accounting".repeat(100), timestamp: 4 });
manager.appendMessage({ role: "user", content: "Later conversation".repeat(500), timestamp: 5 });
const leaf = manager.getLeafId();
assert.deepEqual(buildSessionDisplayMessages(manager).find((message) => message.entryId === compactionId)?.compaction, withTiming.compaction);
assert.equal(manager.getLeafId(), leaf);
manager.appendCustomEntry(COMPACTION_TIMING_TYPE, { compactionEntryId: compactionId, durationMs: -1, reason: "manual" });
assert.equal(compactionTimings(manager.getBranch()).get(compactionId)?.durationMs, 12500);
const legacy = SessionManager.inMemory("/tmp/pi-ark-compaction-stats-legacy");
legacy.appendMessage({ role: "user", content: "Old conversation", timestamp: 1 });
legacy.appendCompaction("Old summary", null, 100000);
const oldStats = buildSessionDisplayMessages(legacy).find((message) => message.role === "compactionSummary")?.compaction;
assert.equal(oldStats?.systemPromptTokens, undefined);
assert.equal(oldStats?.tokensAfter, oldStats?.summaryTokens);
assert.equal(oldStats?.durationMs, undefined);
console.log("compaction statistics checks passed");
